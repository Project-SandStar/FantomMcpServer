/**
 * mapLiteralExpr creates a Map instance
 */
class MapLiteralExpr extends Expr {
  keys: Expr[] = [];
  vals: Expr[] = [];

  constructor(loc: Loc) {
    super(loc, ExprId.mapLiteral);
  }

  override toStr(): string {
    return this.format(e => e.toStr());
  }

  format(f: (e: Expr) => string): string {
    let s = "";

    s += "[";
    if (this.vals.length === 0) {
      s += ":";
    } else {
      this.keys.forEach((k, i) => {
        if (i > 0) {
          s += ",";
        }
        s += f(this.keys[i]);
        s += ":";
        s += f(this.vals[i]);
      });
    }
    s += "]";
    return s;
  }
}

