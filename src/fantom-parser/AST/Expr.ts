/**
 * FieldExpr is used for a field variable access.
 */
class FieldExpr extends NameExpr {
  useAccessor: boolean; // false if access using '&' storage operator

  constructor(
    loc: Loc,
    target: Expr | null = null,
    useAccessor: boolean = true
  ) {
    super(loc, ExprId.field, target, null);
    this.useAccessor = useAccessor;
    this.isSafe = false;
  }

  override isAssignable(): boolean {
    return true;
  }

  override toStr(): string {
    let s = "";
    if (this.target != null) {
      s += this.target;
      s += ".";
    }
    if (this.isSafe) {
      s += "?";
    }
    if (!this.useAccessor) {
      s += "@";
    }
    s += this.name;
    return s;
  }
}

