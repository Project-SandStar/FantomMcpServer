/**
 * BinaryExpr is sued for binary expression with a left hand side and a
 * right hand side including assignment. Note that many common binary
 * operations are actually modeled as a shortcutExpr ro anble method based
 * operator overloading.
 */
class BinaryExpr extends Expr {
  opToken: Token;
  lhs: Expr;
  rhs: Expr;
  //? tempVar: MethodVar | null;

  constructor(lhs: Expr, opToken: Token, rhs: Expr) {
    super(lhs.loc, opToken.toExprId());
    this.lhs = lhs;
    this.opToken = opToken;
    this.rhs = rhs;
  }

  static makeAssign(lhs: Expr, rhs: Expr, leave: boolean = false): BinaryExpr {
    let biExpr = new BinaryExpr(lhs, new Token(TokenType.assign), rhs);
    biExpr.leave = leave;
    return biExpr;
  }

  assignTarget(): Object | null {
    return this.id === ExprId.assign ? this.lhs : null;
  }

  isStmt(): boolean {
    return this.id === ExprId.assign;
  }

  isDefiniteAssign(f: (lhs: Expr) => boolean): boolean {
    if (this.id === ExprId.assign && f(this.lhs)) {
      return true;
    }
    return this.rhs.isDefiniteAssign(f);
  }

  toStr(): string {
    return `(${this.lhs} ${this.opToken} ${this.rhs})`;
  }
}

