// ComplexLiteral
// =======================================================

class ComplexLiteral extends Expr {
  names: string[];
  vals: Expr[];

  constructor(loc: Loc) {
    super(loc, ExprId.complexLiteral);
    this.names = [];
    this.vals = [];
  }

  override toStr(): string {
    return this.doToStr(e => e.toStr());
  }

  doToStr(f: (e: Expr) => string): string {
    let s = "";
    s += "$ctype {";
    this.names.forEach((n, i) => {
      n += `${n} = ${f(this.vals[i])};`;
    });
    s += "}";
    return s;
  }
}

