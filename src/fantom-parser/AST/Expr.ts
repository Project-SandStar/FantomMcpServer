/**
 * ShortcutExpr is used for operator expressions which are a shortcut
 * to a method call:
 *   a + b     =>  a.plus(b)
 *   a - b     =>  a.minus(b)
 *   a * b     =>  a.mult(b)
 *   a / b     =>  a.div(b)
 *   a % b     =>  a.mod(b)
 *   a[b]      =>  a.get(b)
 *   a[b] = c  =>  a.set(b, c)
 *   -a        =>  a.negate()
 *   ++a, a++  =>  a.increment()
 *   --a, a--  =>  a.decrement()
 *   a == b    =>  a.equals(b)
 *   a != b    =>  ! a.equals(b)
 *   a <=>     =>  a.compare(b)
 *   a > b     =>  a.compare(b) > 0
 *   a >= b    =>  a.compare(b) >= 0
 *   a < b     =>  a.compare(b) < 0
 *   a <= b    =>  a.compare(b) <= 0
 */
class ShortcutExpr extends CallExpr {
  op!: ShortcutOp;
  opToken!: Token;
  isPostfixLeave: boolean | null = false; // x++ or x-- (must have Expr.leave set too)
  //? tempVar: MethodVar | null; // temp local var to store += to field/indexed

  constructor(loc: Loc) {
    super(loc, null, null, ExprId.shortcut);
  }

  static makeUnary(loc: Loc, opToken: Token, operand: Expr): ShortcutExpr {
    let expr = new ShortcutExpr(loc);
    expr.op = opToken.toShortcutOp(1);
    expr.opToken = opToken;
    expr.name = expr.op.methodName;
    expr.target = operand;
    return expr;
  }

  static makeBinary(lhs: Expr, opToken: Token, rhs: Expr): ShortcutExpr {
    let expr = new ShortcutExpr(lhs.loc);
    expr.op = opToken.toShortcutOp(2);
    expr.opToken = opToken;
    expr.name = expr.op.methodName;
    expr.target = lhs;
    expr.args.push(rhs);
    return expr;
  }

  static makeGet(loc: Loc, target: Expr, index: Expr): ShortcutExpr {
    let expr = new ShortcutExpr(loc);
    expr.op = ShortcutOp.get();
    expr.opToken = new Token(TokenType.lbracket);
    expr.name = expr.op.methodName;
    expr.target = target;
    expr.args.push(index);
    return expr;
  }

  static makeFrom(from: ShortcutExpr) {
    let expr = new ShortcutExpr(from.loc);
    expr.op = from.op;
    expr.opToken = from.opToken;
    expr.name = from.name;
    expr.target = from.target;
    expr.args = from.args;
    expr.isPostfixLeave = from.isPostfixLeave;
    return expr;
  }

  override assignRequiresTempVar(): boolean {
    return this.isAssignable();
  }

  override assignTarget(): Object | null {
    return this.isAssign() ? this.target : null;
  }

  override isAssignable(): boolean {
    return this.op?.symbol === ShortcutOp.get()?.symbol;
  }

  override isCompare(): boolean {
    return (
      this.op?.symbol === ShortcutOp.eq().symbol ||
      this.op?.symbol === ShortcutOp.cmp().symbol
    );
  }

  override isStmt(): boolean {
    return this.isAssign() || this.op?.symbol === ShortcutOp.set().symbol;
  }

  isAssign(): boolean {
    return this.opToken.isAssign || this.opToken.isIncrementOrDecrement();
  }

  override toStr(): string {
    if (this.op?.symbol == ShortcutOp.get().symbol)
      return `${this.target}[${this.args.at(1)}]`;
    if (this.op?.symbol == ShortcutOp.increment().symbol)
      return this.isPostfixLeave ? `${this.target}++` : `++${this.target}`;
    if (this.op?.symbol == ShortcutOp.decrement().symbol)
      return this.isPostfixLeave ? `${this.target}--` : `--${this.target}`;
    if (this.isAssign())
      return `${this.target} ${this.opToken} ${this.args.at(1)}`;
    if (this.op.degree == 1) return `${this.opToken}${this.target}`;
    if (this.op.degree == 2)
      return `(${this.target} ${this.opToken} ${this.args.at(1)})`;
    return super.toStr();
  }
}

