class ShortcutOp {
  readonly degree: number;
  readonly methodName: string;
  readonly isOperator: boolean;
  readonly symbol: string;

  constructor(
    degree: number,
    symbol: string,
    methodName: string,
    isOperator: boolean = false
  ) {
    this.degree = degree;
    this.symbol = symbol;
    this.methodName = methodName;
    this.isOperator = isOperator;
  }

  static plus(): ShortcutOp {
    return new ShortcutOp(2, "+", "plus", true);
  }

  static minus(): ShortcutOp {
    return new ShortcutOp(2, "-", "minus", true);
  }

  static mult(): ShortcutOp {
    return new ShortcutOp(2, "*", "mult", true);
  }

  static div(): ShortcutOp {
    return new ShortcutOp(2, "/", "div", true);
  }

  static mod(): ShortcutOp {
    return new ShortcutOp(2, "%", "mod", true);
  }

  static negate(): ShortcutOp {
    return new ShortcutOp(1, "-", "negate", true);
  }

  static increment(): ShortcutOp {
    return new ShortcutOp(1, "++", "increment", true);
  }

  static decrement(): ShortcutOp {
    return new ShortcutOp(1, "--", "decrement", true);
  }

  static eq(): ShortcutOp {
    return new ShortcutOp(1, "==", "equals", false);
  }

  static cmp(): ShortcutOp {
    return new ShortcutOp(1, "<=>", "compare", false);
  }

  static get(): ShortcutOp {
    return new ShortcutOp(2, "[]", "get", true);
  }
  static set() {
    return new ShortcutOp(3, "[]=", "set", true);
  }
  static add() {
    return new ShortcutOp(2, ",", "add", true);
  }

  static fromPrefix(prefix: string): ShortcutOp | null {
    return this.prefixes.get(prefix) ?? null;
  }

  static readonly prefixes: Map<string, ShortcutOp> = (() => {
    const map = new Map<string, ShortcutOp>();
    const ops = [
      ShortcutOp.plus(),
      ShortcutOp.minus(),
      ShortcutOp.mult(),
      ShortcutOp.div(),
      ShortcutOp.mod(),
      ShortcutOp.negate(),
      ShortcutOp.increment(),
      ShortcutOp.decrement(),
      ShortcutOp.eq(),
      ShortcutOp.cmp(),
      ShortcutOp.get(),
      ShortcutOp.set(),
      ShortcutOp.add(),
    ];
    ops.forEach(op => map.set(op.methodName, op));
    return map;
  })();
}

