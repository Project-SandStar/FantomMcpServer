/**
 * LiteralExpr puts an Bool, Int, Float, Str, Duration, Uri,
 * or null constant onto the stack
 */
class LiteralExpr extends Expr {
  val: Object | null;

  constructor(loc: Loc, id: ExprId, val: Object | null) {
    super(loc, id);
    this.val = val;
  }

  static makeNull(loc: Loc): LiteralExpr {
    return new LiteralExpr(loc, ExprId.nullLiteral, null);
  }

  static makeTrue(loc: Loc): LiteralExpr {
    return new LiteralExpr(loc, ExprId.trueLiteral, true);
  }

  static makeFalse(loc: Loc): LiteralExpr {
    return new LiteralExpr(loc, ExprId.falseLiteral, false);
  }

  static makeStr(loc: Loc, val: string): LiteralExpr {
    return new LiteralExpr(loc, ExprId.strLiteral, val);
  }

  override isAlwaysNullable(): boolean {
    return this.id == ExprId.nullLiteral;
  }

  override asTableSwitchCase(): number | null {
    return this.val as number;
  }

  toStr(): string {
    switch (this.id) {
      case ExprId.nullLiteral:
        return "null";
      case ExprId.strLiteral:
        return '"' + this.val!.toString().replace("\n", "\\n") + '"';
      case ExprId.typeLiteral:
        return "${val}#";
      case ExprId.uriLiteral:
        return "`$val`";
      default:
        return this.val!.toString();
    }
  }
}

