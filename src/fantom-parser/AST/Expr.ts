/**
 * ListLiteralExpr creates a List instance
 */
class ListLiteralExpr extends Expr {
  vals: Expr[] = [];

  constructor(loc: Loc) {
    super(loc, ExprId.listLiteral);
  }

  static makeFor(loc: Loc, vals: Expr[]) {
    let list = new ListLiteralExpr(loc);
    list.vals = vals;
    return list;
  }

  override toStr(): string {
    return this.format(e => e.toStr());
  }

  format(f: (e: Expr) => string): string {
    let s = "";
    s += "[";
    if (this.vals.length === 0) {
      s += ",";
    } else {
      this.vals.forEach((v: Expr, i: number) => {
        if (i > 0) {
          s += ",";
        }
        s += f(v);
      });
    }
    s += "]";
    return s;
  }
}

