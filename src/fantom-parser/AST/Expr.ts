/**
 * LocaleLiteralExpr: podName::key=defVal
 */
class LocaleLiteralExpr extends Expr {
  pattern: string;
  key: string;
  podName!: string | null;
  def!: string | null;

  constructor(loc: Loc, pattern: string) {
    super(loc, ExprId.localeLiteral);
    this.pattern = pattern;
    this.key = pattern;
    let eq = pattern.indexOf("=");
    if (eq != null) {
      this.key = pattern.slice(0, eq);
      this.def = pattern.slice(eq + 1);
    }

    let colons = this.key.indexOf("::");
    if (colons != null) {
      this.podName = this.key.slice(0, colons);
      this.key = this.key.slice(colons + 2);
    }
  }

  toStr(): string {
    return `<${this.pattern}>`;
  }
}

