/**
 * UnaryExpr is used for unary expressions including !, +.
 * Not that - is mapped to negate() as a shortcut method
 */
class UnaryExpr extends Expr {
  opToken: Token; // operator token type (Token.bang, etc)
  operand: Expr; // operand expression

  constructor(loc: Loc, id: ExprId, opToken: Token, operand: Expr) {
    super(loc, id);
    this.opToken = opToken;
    this.operand = operand;
  }

  override toStr(): string {
    if (this.id == ExprId.cmpNull) {
      return this.operand.toStr() + " == null";
    } else if (this.id === ExprId.cmpNotNull) {
      return this.operand.toStr() + " != null";
    } else return this.opToken.toStr() + this.operand.toStr();
  }
}

