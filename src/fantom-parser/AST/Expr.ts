/**
 * NameExpr is the base class for an identifier expression which has
 * an optional base expression. NameExpr is the base class for
 * UnkownVarExpr and CallExpr which are resolved via CallResolver
 */
abstract class NameExpr extends Expr {
  target: Expr | null; // base target expression or null
  name: string | null; // name of variable (local/field/method)
  isSafe: boolean; // if ?. operator

  constructor(loc: Loc, id: ExprId, target: Expr | null, name: string | null) {
    super(loc, id);
    this.target = target;
    this.name = name;
    this.isSafe = false;
  }

  override isAlwaysNullable(): boolean {
    return this.isSafe;
  }

  toStr(): string {
    if (this.target != null) {
      return this.target.toStr() + (this.isSafe ? "?." : ".") + this.name;
    } else {
      return this.name!;
    }
  }
}

