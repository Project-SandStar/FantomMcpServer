const bottomNavItem = { href: '/documentation', label: 'Documentation', icon: AcademicCapIcon };

export function Nav() {
  const pathname = usePathname();
  const { user, logout } = useAuth();

  return (
    <nav className="w-64 bg-gray-900 text-white min-h-screen p-4 flex flex-col">
      <div className="mb-4">
        <h1 className="text-xl font-bold">Fantom MCP</h1>
        <p className="text-xs text-gray-400 mt-1">Dashboard</p>
      </div>

      {/* Instance Selector */}
      <div className="mb-6">
        <InstanceSelector compact />
      </div>

      <ul className="space-y-1 flex-1">
        {navItems.map((item) => {
          const isActive = pathname === item.href ||
            (item.href !== '/' && pathname?.startsWith(item.href));
          const Icon = item.icon;
          return (
            <li key={item.href}>
              <Link
                href={item.href}
                className={`flex items-center gap-3 px-4 py-2.5 rounded-lg transition-colors ${
                  isActive
                    ? 'bg-blue-600 text-white'
                    : 'text-gray-300 hover:bg-gray-800 hover:text-white'
                }`}
              >
                <Icon />
                <span>{item.label}</span>
              </Link>
            </li>
          );
        })}
      </ul>

      {/* Bottom Navigation - Documentation */}
      <div className="mt-auto pt-4 border-t border-gray-700">
        <ul className="space-y-1">
          <li>
            <Link
              href={bottomNavItem.href}
              className={`flex items-center gap-3 px-4 py-2.5 rounded-lg transition-colors ${
                pathname === bottomNavItem.href || pathname?.startsWith(bottomNavItem.href)
                  ? 'bg-blue-600 text-white'
                  : 'text-gray-300 hover:bg-gray-800 hover:text-white'
              }`}
            >
              <bottomNavItem.icon />
              <span>{bottomNavItem.label}</span>
            </Link>
          </li>
        </ul>
      </div>

      {/* User Info and Logout */}
      {user && (
        <div className="pt-4 border-t border-gray-700">
          <div className="flex items-center gap-3 px-4 py-2">
            <div className="w-8 h-8 bg-blue-600 rounded-full flex items-center justify-center">
              <UserIcon />
            </div>
            <div className="flex-1 min-w-0">
              <p className="text-sm font-medium text-white truncate">{user.username}</p>
              <p className="text-xs text-gray-400">{user.role}</p>
            </div>
          </div>
          <button
            onClick={logout}
            className="w-full flex items-center gap-3 px-4 py-2.5 mt-2 text-gray-300 hover:bg-gray-800 hover:text-white rounded-lg transition-colors"
          >
            <LogOutIcon />
            <span>Sign out</span>
          </button>
        </div>
      )}

      {/* Footer */}
      <div className="pt-4">
        <p className="text-xs text-gray-500 text-center">
          MCP Fantom Server
        </p>
      </div>
    </nav>
  );
}
